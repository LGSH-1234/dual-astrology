import { readFile, mkdir, writeFile } from 'node:fs/promises';

const files = {
  'src/lib/types.ts': 'types.ts',
  'src/lib/content.ts': 'content.ts',
  'src/lib/ai/validate.ts': 'validate.ts',
  'src/lib/ai/mock.ts': 'mock.ts',
  'server/deepseek.ts': 'deepseek.ts',
  'server/cloud.ts': 'cloud.ts',
};
const destination = 'supabase/functions/_shared';
await mkdir(destination, { recursive: true });
for (const [source, name] of Object.entries(files)) {
  const text = (await readFile(source, 'utf8')).replace(/from ['"](?:\.\.?\/)+([^'"]+)['"]/g,
    (_match, path) => `from './${path.split('/').pop()}.ts'`);
  await writeFile(`${destination}/${name}`, `// Generated by scripts/sync-edge-shared.mjs; edit ${source}.\n${text}`);
}
console.log('Supabase shared code synchronized.');
